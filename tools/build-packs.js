#!/usr/bin/env node
/* Folds the content and ship mods in mods/ into the base game as js/packs.js.
   Run after editing any of those mods:  node tools/build-packs.js
   Rules mods, script mods, challenge packs and campaigns stay optional in the Mods library. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), ix = JSON.parse(fs.readFileSync(path.join(root, 'mods/index.json'), 'utf8')).mods;
const KEEP = new Set(['content', 'ships']);
// ships that came unlocked in their mod get a requirement, so new hulls are still something to earn
const UNLOCK = { lanternship:{ sector:2 }, lanternb:{ kills:12 }, anvil:{ kills:15 }, anvilb:{ sector:5 }, tideship:{ sector:4 }, tideb:{ kills:35 },
  xh_lance:{ sector:3 }, dh_beehive:{ kills:30 }, pk_corsair:{ sector:5 }, bp_crowbar:{ kills:40 }, jollyroger:{ sector:6 }, rd_turncoat:{ sector:7 } };
const packs = [];
for(const m of ix){ if(!KEEP.has(m.kind)) continue; const d = JSON.parse(fs.readFileSync(path.join(root, 'mods', m.file), 'utf8'));
  const p = { file:m.file, name:d.name };
  for(const k in d){ if(!Array.isArray(d[k]) || !d[k].length) continue; p[k] = d[k].map(o => o && UNLOCK[o.id] && k==='ships' && !o.unlock ? Object.assign({}, o, { unlock:UNLOCK[o.id] }) : o); }
  packs.push(p); }
const out = `'use strict';
/* =========================================================================
   Built-in content packs. These began as mods and are now part of the base
   game: extra ships, weapons, drones, augments, races, enemies, sectors and
   events. GENERATED by tools/build-packs.js from the JSON files in mods/;
   edit those and re-run the script rather than editing this file.
   ========================================================================= */
const PACKS = ${JSON.stringify(packs)};
const PACK_NAMES = new Set(PACKS.map(p => p.name)), PACK_FILES = new Set(PACKS.map(p => p.file));
(function(){ for(const p of PACKS) for(const k in p){ if(k==='file' || k==='name' || !BASE[k] || !Array.isArray(p[k])) continue;
  for(const o of p[k]) if(o && o.id!=null && !BASE[k][o.id]) BASE[k][o.id] = Object.assign({}, o, { pack:p.name }); } })();
`;
fs.writeFileSync(path.join(root, 'js/packs.js'), out);
console.log(`js/packs.js: ${packs.length} packs, ${(out.length/1024).toFixed(0)} KB`);
